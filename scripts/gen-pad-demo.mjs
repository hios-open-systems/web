import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { demoLayers } from './pad-demo-fixture.mjs';

// Reuse the companion's actual renderer; only replace its live transport and
// add demo controls. Regenerate after changes to the companion mirror.
const source = 'projects/pad/companion/src/web/public/index.html';
let html = await readFile(source, 'utf8');
const transport = `
  // Local sample transport: no HTTP, SSE, USB, BLE or host keyboard events.
  const demoLayers = ${JSON.stringify(demoLayers)};
  let selected = 0, demoVolume = 42, pressed = 0;
  const demoOutput = document.getElementById('demo-output');
  function demoRender() {
    const layer = demoLayers[selected];
    render({lay:selected, layer:{...layer,count:demoLayers.length}, b:pressed,
      tp:0, bat:255, os:'demo', mic:false, vol:demoVolume, em:layer.em});
    setBadge('bLink','DEMO','warn');
    document.getElementById('lgrp').textContent = 'ejemplo · ' + (selected+1) + '/3';
  }
  document.getElementById('demo-layer').onchange = e => {
    selected = Number(e.target.value); pressed = 0;
    demoOutput.textContent = 'Capa: ' + demoLayers[selected].n; demoRender();
  };
  document.getElementById('demo-volume').oninput = e => {
    demoVolume = Number(e.target.value);
    demoOutput.textContent = 'Volumen simulado: ' + demoVolume + '%'; demoRender();
  };
  Array.from(keysEl.children).forEach((key,i) => {
    key.tabIndex = 0; key.setAttribute('role','button');
    function activate() {
      pressed = 1 << i;
      demoOutput.textContent = 'Simulado: ' + (demoLayers[selected].labels[i] || 'Sin asignar');
      demoRender();
    }
    key.onclick = activate;
    key.onkeydown = e => { if(e.key === 'Enter' || e.key === ' ') { e.preventDefault(); activate(); } };
  });
  const wrap = document.querySelector('.wrap');
  function resizeDemo() {
    const scale = Math.min(1.15, Math.max(.1, (document.documentElement.clientWidth-36)/480));
    wrap.style.setProperty('--s', scale);
  }
  window.addEventListener('resize', resizeDemo); resizeDemo(); demoRender();
`;
const marker = '  // SSE';
if (!html.includes(marker)) throw new Error('Companion transport changed; review demo generation.');
html = html.slice(0, html.indexOf(marker)) + transport + '\n</script>\n</body>\n</html>\n';
// Remove the unused config preview: the published demo contains no network calls.
html = html.replace(/  async function previewFromNav\(\)[\s\S]*?(?=  \/\/ Local sample transport)/, '');
html = html.replace('<title>HIOS PAD · Espejo</title>', '<title>HIOS PAD · Demo local</title>');
html = html.replace('<meta charset="utf-8">', `<meta charset="utf-8">
<meta http-equiv="Content-Security-Policy" content="default-src 'none'; script-src 'unsafe-inline'; style-src 'unsafe-inline'; connect-src 'none'; form-action 'none'; base-uri 'none'">`);
html = html.replace(/  <h1>[\s\S]*?<div id="conn">.*?<\/div>/, `
  <h1>HIOS PAD <span class="tag">demo local</span></h1>
  <p class="note">Interfaz del espejo del companion · datos de ejemplo · sin hardware</p>
  <div class="demo-controls">
    <label>Capa <select id="demo-layer" aria-label="Capa"><option value="0">Edición</option><option value="1">Multimedia</option><option value="2">Dev</option></select></label>
    <label>Volumen simulado <input id="demo-volume" type="range" min="0" max="100" value="42"></label>
  </div>`);
html = html.replace(/<div class="note">Espejo en vivo[\s\S]*?<\/div>/, '<p id="demo-output" class="note" role="status" aria-live="polite">Pulsá una tecla para ver su etiqueta. No se ejecutan acciones en tu PC.</p>');
html = html.replace('</style>', `
  .demo-controls{display:flex;flex-wrap:wrap;gap:16px;justify-content:center;max-width:100%}
  .demo-controls label{display:flex;align-items:center;gap:8px;font-size:13px}
  select{background:#161b22;color:#e6edf3;border:1px solid #30363d;padding:6px;border-radius:6px}
  input[type=range]{max-width:130px}
  .key{cursor:pointer}.key:focus-visible{outline:3px solid #fff;outline-offset:-4px}
  .note{margin:0;line-height:1.6}.hdr{gap:6px}.badge{padding:3px 5px}
</style>`);
await mkdir('public/demos/pad', { recursive: true });
await writeFile('public/demos/pad/index.html', '<!-- Generated by scripts/gen-pad-demo.mjs from companion mirror. -->\n' + html);
console.log('Generated offline PAD demo from companion renderer.');
