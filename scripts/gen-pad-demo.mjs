function render(f) {
  const lay = f.layer || { n: '?', color: 0x07ff, count: 0, labels: [] };
  const accent = rgb565ToHex(lay.color || 0x07ff);
  document.documentElement.style.setProperty('--accent', accent);
  document.getElementById('lname').textContent = lay.n || '—';
  document.getElementById('lidx').textContent  = '[' + ((f.lay ?? 0) + 1) + '/' + (lay.count || 16) + ']';
  document.getElementById('tp').textContent    = TP_NAMES[f.tp] || '—';
  document.getElementById('os').textContent    = f.os || '?';

  const wizb = document.getElementById('wizb');
  if (f.lay === 4 || lay.n === 'Luces') {
    wizb.hidden = false;
    wizb.textContent = f.wiz !== false ? 'WiZ ON' : 'WiZ OFF';
    wizb.classList.toggle('on', f.wiz !== false);
  } else {
    wizb.hidden = true;
  }

  const micEl = document.getElementById('mic');
  const muted = Boolean(f.mic);
  micEl.textContent = muted ? 'MUTE' : 'MIC ON';
  const micCol = muted ? '#f43f5e' : '#22d37a';
  document.getElementById('mic-capsule')?.setAttribute('stroke', micCol);
  document.getElementById('mic-arc')?.setAttribute('stroke', micCol);
  const slash = document.getElementById('mic-slash');
  if (slash) slash.setAttribute('visibility', muted ? 'visible' : 'hidden');

  for (let i = 0; i < 10; i++) {
    const lbl = (lay.labels && lay.labels[i]) || '';
    const pressed = ((f.b >> i) & 1) === 1;
    cells[i].classList.toggle('empty', lbl.length === 0);
    cells[i].classList.toggle('pressed', pressed);
    cells[i].disabled = lbl.length === 0;
    cells[i].setAttribute('aria-label', (i + 1) + ' ' + (lbl || 'Vacío'));
    cells[i].querySelector('.lbl').textContent = lbl || '—';
    const well = cells[i].querySelector('.well');
    well.innerHTML = lbl.length > 0 ? svgGlyphFor(lbl) : '';
  }

  document.getElementById('enc').textContent = EM_NAMES[f.em] || 'Capa';
  const needle = document.getElementById('enc-needle');
  if (needle) {
    const rad = (encAngle * Math.PI) / 180;
    needle.setAttribute('x2', (15 + 9 * Math.cos(rad)).toFixed(1));
    needle.setAttribute('y2', (15 + 9 * Math.sin(rad)).toFixed(1));
  }

  const v = Math.max(0, Math.min(100, f.vol ?? 0));
  document.getElementById('volnum').textContent = v;
  document.getElementById('volfill').style.width = v + '%';
  renderOverlay();
}

function triggerKey(i) {
  const lbl = state.layer.labels[i];
  if (!lbl) return;
  state.b = 1 << i;
  encAngle = (encAngle + 24) % 360;
  if (lbl === 'Mute' || lbl === 'Mic') state.mic = !state.mic;
  if (lbl === 'On/Off' || lbl === 'Off') state.wiz = !state.wiz;
  toast.textContent = 'Simulado: ' + lbl;
  render(state);
  window.setTimeout(() => {
    state.b = 0;
    render(state);
  }, 180);
}

layerSelect.addEventListener('change', () => {
  const idx = Number(layerSelect.value) || 0;
  const layer = LAYERS[idx] || LAYERS[0];
  state.lay = idx;
  state.em = layer.em;
  state.layer = { ...layer, count: 16 };
  currentView = 'keys';
  viewSelect.value = 'keys';
  encAngle = (encAngle + 30) % 360;
  toast.textContent = 'Capa: ' + layer.n;
  render(state);
});

viewSelect.addEventListener('change', () => {
  currentView = viewSelect.value;
  toast.textContent = 'Pantalla: ' + viewSelect.options[viewSelect.selectedIndex].text;
  renderOverlay();
});

volInput.addEventListener('input', () => {
  state.vol = Number(volInput.value) || 0;
  encAngle = -90 + Math.round((state.vol / 100) * 270);
  toast.textContent = 'Volumen: ' + state.vol + '%';
  render(state);
});

themeBtn.addEventListener('click', () => {
  const next = document.body.dataset.theme === 'light' ? 'dark' : 'light';
  document.body.dataset.theme = next;
  toast.textContent = 'Tema: ' + (next === 'light' ? 'Claro' : 'Oscuro');
});

