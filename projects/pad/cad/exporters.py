"""Dependency-free CAD and glTF outputs; volumes are conceptual, not printable."""
import json
import math
import struct
from geometry import world_vertices

COLORS = {
    "structure": [0.22, 0.26, 0.30, 0.16],
    "display": [0.10, 0.14, 0.19, 1],
    "controls": [0.28, 0.32, 0.37, 1],
    "power": [0.84, 0.51, 0.22, 1],
    "electronics": [0.15, 0.55, 0.48, 1],
    "audio": [0.43, 0.38, 0.67, 1],
    "clearance": [0.88, 0.35, 0.24, 0.2],
}
# Vertex order is itertools.product([-1,1], repeat=3).
FACES = [(0,1,3,2), (4,6,7,5), (0,4,5,1),
         (2,3,7,6), (0,2,6,4), (1,5,7,3)]


def write_scad(scenes, path):
    lines = ["// Generated by build.py. Edit model.py / layouts.py / components.json.",
             "// MM. Concept envelopes; not manufacturing geometry.",
             "layout_index = 1; // [0:Lineal,1:Cuadricula,2:Doble fila]",
             "screen_angle = 55; // [0:1:75]",
             "show_clearances = false;", "show_envelope = true;", "$fn=48;",
             "module item(s,c,col,shape) {",
             "  color(col) translate(c)",
             "    if(shape==\"cylinder\") cylinder(d=s[0], h=s[2], center=true);",
             "    else cube(s, center=true);", "}"]
    for index, scene in enumerate(scenes):
        lines.append(f"if (layout_index == {index}) {{")
        for p in scene["parts"]:
            color = COLORS[p["category"]]
            prefix = "if(show_clearances) " if p.get("reserve") else ""
            if p.get("container"):
                prefix += "if(show_envelope) "
            if p.get("moving"):
                prefix += f"translate({json.dumps(scene['pivot'])}) rotate([screen_angle,0,0]) "
            args = [p["size"],p["center"],color,p.get("shape","box")]
            lines.append("  // "+p["label"])
            lines.append("  "+prefix+"item("+",".join(json.dumps(v) for v in args)+");")
        lines.append("}")
    path.write_text("\n".join(lines)+"\n", encoding="utf-8", newline="\n")


def triangulate(p, scene):
    verts = world_vertices(p,scene,scene["angle"])
    # Right-handed z-up mm -> right-handed y-up meters.
    verts = [[x/1000,z/1000,-y/1000] for x,y,z in verts]
    positions, normals = [], []
    for face in FACES:
        for ids in [(face[0],face[1],face[2]), (face[0],face[2],face[3])]:
            a,b,c = [verts[i] for i in ids]
            u,v = [[q[i]-a[i] for i in range(3)] for q in [b,c]]
            n = [u[1]*v[2]-u[2]*v[1],u[2]*v[0]-u[0]*v[2],u[0]*v[1]-u[1]*v[0]]
            length = math.sqrt(sum(t*t for t in n))
            positions += a+b+c
            normals += [t/length for t in n]*3
    return positions,normals


def add_accessor(doc, binary, values, positions=False):
    offset = len(binary)
    binary.extend(struct.pack("<"+"f"*len(values), *values))
    view = len(doc["bufferViews"])
    doc["bufferViews"].append(dict(buffer=0,byteOffset=offset,
                                   byteLength=len(values)*4,target=34962))
    acc = dict(bufferView=view,componentType=5126,count=len(values)//3,type="VEC3")
    if positions:
        acc["min"] = [min(values[i::3]) for i in range(3)]
        acc["max"] = [max(values[i::3]) for i in range(3)]
    doc["accessors"].append(acc)
    return len(doc["accessors"])-1


def write_glb(scene, path):
    doc = dict(asset={"version":"2.0","generator":"HIOS PAD volumetric study"},
               scene=0,scenes=[{"nodes":[]}],nodes=[],meshes=[],materials=[],
               bufferViews=[],accessors=[])
    binary = bytearray()
    for category,color in COLORS.items():
        doc["materials"].append(dict(name=category,doubleSided=True,
            alphaMode="BLEND" if color[3]<1 else "OPAQUE",
            pbrMetallicRoughness=dict(baseColorFactor=color,metallicFactor=0,roughnessFactor=0.8)))
    for p in scene["parts"]:
        if p.get("reserve"):
            continue
        positions,normals = triangulate(p,scene)
        pa = add_accessor(doc,binary,positions,True)
        na = add_accessor(doc,binary,normals)
        mat = list(COLORS).index(p["category"])
        doc["meshes"].append({"primitives":[{"attributes":{"POSITION":pa,"NORMAL":na},"material":mat}]})
        doc["nodes"].append({"name":p["label"],"mesh":len(doc["meshes"])-1,
                             "extras":{"id":p["id"],"size_mm":p["size"],"status":"provisional envelope"}})
        doc["scenes"][0]["nodes"].append(len(doc["nodes"])-1)
    doc["buffers"] = [{"byteLength":len(binary)}]
    doc["extras"] = {"units":"meters","source_units":"mm","base_mm":scene["base"],
                      "display_angle_degrees":scene["angle"],"manufacturing_ready":False}
    payload = json.dumps(doc,separators=(",",":"),ensure_ascii=False).encode()
    payload += b" " * (-len(payload)%4)
    total = 12+8+len(payload)+8+len(binary)
    path.write_bytes(struct.pack("<III",0x46546C67,2,total)
                     + struct.pack("<II",len(payload),0x4E4F534A)+payload
                     + struct.pack("<II",len(binary),0x004E4942)+binary)
